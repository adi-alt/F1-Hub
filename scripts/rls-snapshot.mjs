#!/usr/bin/env node
// READ-ONLY snapshot of the database's client-facing security state, taken immediately before
// supabase/migrations/20260929_rls_lockdown.sql is applied, and written out as the SQL that would
// restore it (docs/audit/RLS_LOCKDOWN_CHECKLIST.md). It never writes to the database: everything runs
// inside `begin read only` and is rolled back.
//
//   node scripts/rls-snapshot.mjs <output-dir>
//
// Writes <output-dir>/rls-snapshot-<timestamp>.json (the raw catalog rows) and
// <output-dir>/rls-restore-<timestamp>.sql (the rollback). Use a directory OUTSIDE the repository:
// the snapshot names roles and tables, not data, but it describes the project's security posture.
// DATABASE_URL is read from .env.local, like the other scripts; RLS_SNAPSHOT_DATABASE_URL overrides it
// (used to rehearse against a disposable database).

import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const outDir = process.argv[2];
if (!outDir) {
  console.error("usage: node scripts/rls-snapshot.mjs <output-dir outside the repo>");
  process.exit(1);
}
const connectionString =
  process.env.RLS_SNAPSHOT_DATABASE_URL ??
  (fs.readFileSync(new URL("../.env.local", import.meta.url), "utf8").match(/^DATABASE_URL=(.*)$/m) ?? [])[1];
if (!connectionString) {
  console.error("DATABASE_URL not found in .env.local");
  process.exit(1);
}

const CLIENT_ROLES = ["anon", "authenticated"];
// Created by 20260929_rls_lockdown.sql; dropped on restore only if they did not exist at snapshot time.
const MIGRATION_FUNCTIONS = ["public.is_group_member(uuid)", "public.is_group_staff(uuid)", "public.current_user_is_admin()"];

const client = new pg.Client({ connectionString, ssl: /localhost|127\.0\.0\.1/.test(connectionString) ? false : { rejectUnauthorized: false } });
await client.connect();
await client.query("begin read only");
const q = async (sql, params = []) => (await client.query(sql, params)).rows;
let snapshot;
try {
  snapshot = {
    takenAt: new Date().toISOString(),
    server: (await q(`select current_setting('server_version') as v`))[0].v,
    // The migration's `alter default privileges` affects only the role that runs it, so the restore
    // resets only that role's defaults (it may not be allowed to touch another role's, e.g. supabase_admin).
    migratingRole: (await q(`select current_user::text as r`))[0].r,
    rls: await q(`select c.relname::text as relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c
                   where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p') order by 1`),
    policies: await q(`select tablename::text, policyname::text, permissive, cmd, roles::text[] as roles, qual, with_check
                         from pg_policies where schemaname = 'public' order by 1, 2`),
    // ::text casts: information_schema columns are domain types, whose arrays the driver can't parse.
    tableGrants: await q(`select table_name::text, grantee::text, array_agg(privilege_type::text order by privilege_type::text) as privs
                            from information_schema.role_table_grants
                           where table_schema = 'public' and grantee = any($1) group by 1, 2 order by 1, 2`, [CLIENT_ROLES]),
    functions: await q(`select p.oid::regprocedure::text as sig, p.proacl is null as default_acl, p.proconfig,
                               coalesce((select array_agg((case when a.grantee = 0 then 'public' else pg_get_userbyid(a.grantee)::text end) order by 1)
                                           from aclexplode(p.proacl) a where a.privilege_type = 'EXECUTE'), '{}'::text[]) as execute_grantees
                          from pg_proc p where p.pronamespace = 'public'::regnamespace order by 1`),
    defaultAcls: await q(`select pg_get_userbyid(d.defaclrole)::text as owner, d.defaclobjtype::text as objtype,
                                 pg_get_userbyid(a.grantee)::text as grantee, array_agg(a.privilege_type::text order by a.privilege_type::text) as privs
                            from pg_default_acl d cross join aclexplode(d.defaclacl) a
                           where d.defaclnamespace = 'public'::regnamespace and d.defaclobjtype = 'r' and pg_get_userbyid(a.grantee) = any($1)
                           group by 1, 2, 3 order by 1, 3`, [CLIENT_ROLES]),
  };
} finally {
  await client.query("rollback").catch(() => {});
  await client.end();
}

const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;
const role = (r) => (r === "public" ? "public" : ident(r));
const lines = [
  `-- Restores the client-facing security state captured ${snapshot.takenAt} (server ${snapshot.server}).`,
  `-- Generated by scripts/rls-snapshot.mjs. Rolls back 20260929_rls_lockdown.sql ONLY; do not use after later migrations.`,
  `-- Counts: ${snapshot.rls.length} tables, ${snapshot.policies.length} policies, ${snapshot.tableGrants.length} client table grants, ${snapshot.functions.length} functions, ${snapshot.defaultAcls.length} default-privilege entries.`,
  `set local lock_timeout = '5s';`,
  `set local search_path = public, pg_temp;`,
  `-- 1. Policies: drop whatever exists now, recreate the snapshot's (step 5).`,
  `do $$ declare p record; begin for p in select policyname, tablename from pg_policies where schemaname = 'public' loop execute format('drop policy %I on public.%I', p.policyname, p.tablename); end loop; end $$;`,
  `-- 2. RLS flags.`,
  ...snapshot.rls.map((t) => `alter table public.${ident(t.relname)} ${t.relrowsecurity ? "enable" : "disable"} row level security;` + (t.relforcerowsecurity ? ` alter table public.${ident(t.relname)} force row level security;` : "")),
  `-- 3. Client table privileges.`,
  `revoke all on all tables in schema public from anon, authenticated;`,
  ...snapshot.tableGrants.map((g) => `grant ${g.privs.join(", ")} on public.${ident(g.table_name)} to ${ident(g.grantee)};`),
  `-- 4. Default privileges for future tables - only ${snapshot.migratingRole}'s, the only ones the migration changes.`,
  ...snapshot.defaultAcls.filter((d) => d.owner !== snapshot.migratingRole).map((d) => `-- (unchanged by the migration, not touched: default privileges of ${d.owner} for ${d.grantee}: ${d.privs.join(", ")})`),
  `alter default privileges for role ${ident(snapshot.migratingRole)} in schema public revoke all on tables from anon, authenticated;`,
  ...snapshot.defaultAcls.filter((d) => d.owner === snapshot.migratingRole).map((d) => `alter default privileges for role ${ident(d.owner)} in schema public grant ${d.privs.join(", ")} on tables to ${ident(d.grantee)};`),
  `-- 5. Policies as they were.`,
  ...snapshot.policies.map(
    (p) =>
      `create policy ${ident(p.policyname)} on public.${ident(p.tablename)} as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${p.roles.map(role).join(", ")}` +
      (p.qual ? ` using (${p.qual})` : "") +
      (p.with_check ? ` with check (${p.with_check})` : "") +
      ";",
  ),
  `-- 6. Function privileges and settings for functions that existed at snapshot time.`,
  ...snapshot.functions.flatMap((f) => [
    `revoke all on function ${f.sig} from public, anon, authenticated;`,
    ...(f.default_acl ? [`grant execute on function ${f.sig} to public;`] : f.execute_grantees.filter((g) => ["public", ...CLIENT_ROLES].includes(g)).map((g) => `grant execute on function ${f.sig} to ${role(g)};`)),
    `alter function ${f.sig} reset all;`,
    ...(f.proconfig ?? []).map((c) => {
      const i = c.indexOf("=");
      return `alter function ${f.sig} set ${c.slice(0, i)} = '${c.slice(i + 1).replace(/'/g, "''")}';`;
    }),
  ]),
  `-- 7. Functions the lockdown created (none of them existed at snapshot time).`,
  ...MIGRATION_FUNCTIONS.filter((sig) => !snapshot.functions.some((f) => f.sig === sig)).map((sig) => `drop function if exists ${sig};`),
  `-- 8. Ledger.`,
  `delete from public.schema_migrations where name = '20260929_rls_lockdown.sql';`,
];

fs.mkdirSync(outDir, { recursive: true });
const stamp = snapshot.takenAt.replace(/[:.]/g, "-");
const jsonPath = path.join(outDir, `rls-snapshot-${stamp}.json`);
const sqlPath = path.join(outDir, `rls-restore-${stamp}.sql`);
fs.writeFileSync(jsonPath, JSON.stringify(snapshot, null, 1), { mode: 0o600 });
fs.writeFileSync(sqlPath, lines.join("\n") + "\n", { mode: 0o600 });
console.log(`snapshot: ${snapshot.rls.length} tables (${snapshot.rls.filter((t) => !t.relrowsecurity).length} without RLS), ${snapshot.policies.length} policies, ${snapshot.tableGrants.length} client table grants, ${snapshot.functions.length} functions, ${snapshot.defaultAcls.length} default-privilege entries`);
console.log(`wrote ${jsonPath}`);
console.log(`wrote ${sqlPath}`);
